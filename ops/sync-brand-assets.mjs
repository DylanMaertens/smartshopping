// Reproducible copies of the approved Poduna identity; no AI generation here.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const kit = resolve(root, 'output/branding/poduna/v1');
const mobile = resolve(root, 'mobile/assets/brand');
const web = resolve(root, 'web/dist/assets/brand');
await Promise.all([mkdir(mobile, { recursive: true }), mkdir(web, { recursive: true })]);
for (const [from, to] of [
  ['icons/app-icon-1024.png', 'icon.png'],
  ['icons/android-foreground-432.png', 'adaptive-foreground.png'],
  ['png/poduna-symbol-green-1024.png', 'splash.png'],
]) await copyFile(resolve(kit, from), resolve(mobile, to));
for (const [from, to] of [
  ['svg/poduna-symbol-green.svg', 'symbol.svg'],
  ['svg/poduna-logo-green.svg', 'logo.svg'],
  ['svg/poduna-logo-ivory.svg', 'logo-ivory.svg'],
  ['icons/favicon.ico', 'favicon.ico'],
  ['icons/apple-touch-icon.png', 'apple-touch-icon.png'],
]) await copyFile(resolve(kit, from), resolve(web, to));
const source = await readFile(resolve(kit, 'source/symbol.svg'), 'utf8');
const paths = [...source.matchAll(/<path d="([^"]+)"/g)].map(match => match[1].replace(/\s+/g, ' ').trim());
if (paths.length !== 3) throw new Error('Unexpected brand symbol: review paths before publishing.');
await writeFile(resolve(root, 'mobile/src/components/podunaPaths.ts'),
  '// Generated by ops/sync-brand-assets.mjs from the approved SVG.\nexport const PODUNA_PATHS = ' + JSON.stringify(paths, null, 2) + ' as const;\n');
console.log('Poduna: mobile and web brand assets updated.');
